#!/usr/bin/env node
/* Refreshes data/snapshot.js: the copy of the sheet the page shows instantly
   and falls back to if Google Sheets can't be reached.

   node tools/update-snapshot.mjs           → download the live sheet (links from site-config.js)
   node tools/update-snapshot.mjs --local   → use sheet-template/Stories.csv + Stats.csv

   STORIES_CSV / STATS_CSV environment variables override site-config.js. */
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const cfg = await readFile(new URL('site-config.js', root), 'utf8');
const pick = (k) => (cfg.match(new RegExp(k + "\\s*:\\s*'([^']*)'")) || [])[1] || '';
const local = process.argv.includes('--local');
const src = {
  stories: process.env.STORIES_CSV || pick('STORIES_CSV'),
  stats: process.env.STATS_CSV || pick('STATS_CSV'),
};

async function get(url, file, mustHave) {
  let text;
  if (local || !url) {
    text = await readFile(new URL('sheet-template/' + file, root), 'utf8');
  } else {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) throw new Error(`${file}: HTTP ${res.status} from ${url}`);
    text = await res.text();
  }
  text = text.replace(/^﻿/, '');
  const head = text.split(/\r?\n/, 1)[0].toLowerCase();
  if (!mustHave.every((h) => head.includes(h))) {
    throw new Error(`${file}: first row should contain ${mustHave.join(', ')}. Is the tab published as CSV?`);
  }
  return text;
}

const stories = await get(src.stories, 'Stories.csv', ['type', 'name']);
const stats = await get(src.stats, 'Stats.csv', ['where', 'value']);
const body = JSON.stringify({ generated: new Date().toISOString(), stories, stats });
await writeFile(
  new URL('data/snapshot.js', root),
  '/* Auto-generated by tools/update-snapshot.mjs. Do not edit by hand: edit the Google Sheet. */\n' +
    'window.SS_SNAPSHOT = ' + body + ';\n'
);
const rows = stories.trim().split(/\r?\n/).length - 1;
console.log(`data/snapshot.js updated from ${local || !src.stories ? 'sheet-template' : 'Google Sheets'} (~${rows} lines of stories)`);
